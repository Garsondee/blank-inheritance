/**
 * Generates design/ui/redaction-sample.js — the clearance-tiered document the
 * style prototype displays.
 *
 * The prototype must show what the REAL generator produces, not hand-written
 * markup that resembles it, or reviewing the prototype tells us nothing about
 * what players will see. So the sample is built by core/redact.mjs and
 * committed, and test/tier1-redaction.test.mjs fails if the committed file
 * drifts from what the generator now emits.
 *
 * Run:  node design/ui/build-redaction-sample.mjs
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { redactHtml } from "../../module/blank-inheritance/scripts/core/redact.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));

/**
 * The uncensored source, authored the way campaign JSON will author it.
 * c = the clearance a reader needs. This string is the ONLY place the
 * classified text exists; it never ships to a player at any tier.
 */
export const SAMPLE_SOURCE =
  `<p>Recovery of the unit designated <redact c="2">HOLLOW-3</redact> was completed at ` +
  `04:11 on the eleventh. The pilot was <redact c="3">removed from the cockpit by cutting ` +
  `crew after the umbilical failed to release</redact> and is listed as ` +
  `<redact c="2">unrecoverable</redact>.</p>\n` +
  `<h2>Annex B &mdash; Disposition</h2>\n` +
  `<p>Sync figures at time of contact exceeded <redact c="3">the ceiling this office has ` +
  `certified for any candidate</redact>. The Directorate&rsquo;s position is that ` +
  `<redact c="4">the excavation itself is selecting its pilots, and has been since the ` +
  `first dig</redact>, and no further comment is authorised.</p>`;

export const SAMPLE_SALT = "order-14";
export const SAMPLE_TIERS = [1, 2, 3];

export function buildSample() {
  const versions = {};
  for (const tier of SAMPLE_TIERS) {
    const { html, redactionCount } = redactHtml(SAMPLE_SOURCE, tier, { salt: SAMPLE_SALT });
    versions[tier] = { html, redactionCount };
  }
  return versions;
}

export function renderSampleFile(versions) {
  return (
    "/* GENERATED by design/ui/build-redaction-sample.mjs — do not edit by hand.\n" +
    "   Produced by module/blank-inheritance/scripts/core/redact.mjs so the\n" +
    "   prototype shows exactly what the module will publish. */\n" +
    "window.BI_REDACTION_SAMPLE = " +
    JSON.stringify(versions, null, 2) +
    ";\n"
  );
}

// Only write when run directly, so the test can import the builders.
if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  const out = path.join(here, "redaction-sample.js");
  writeFileSync(out, renderSampleFile(buildSample()), "utf8");
  console.log(`wrote ${out}`);
}
