/**
 * Shared plumbing for the QC bot (design/qc-bot.md): where its files live, what it may write, and how JSON is read and
 * written the way this repo stores it (two spaces, a final newline, the file's own line endings).
 *
 * Pure of the network and of git. Nothing here changes a file unless it is `writeJson`.
 */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");

export const QC_DIR = "reviews/qc";
export const REPORTS_DIR = `${QC_DIR}/reports`;
export const DECISIONS_DIR = `${QC_DIR}/decisions`;
export const FOCUS_FILE = `${QC_DIR}/focus.json`;

export const lf = (s) => String(s).replace(/\r\n?/g, "\n");
export const sha = (text, n = 16) => crypto.createHash("sha256").update(text).digest("hex").slice(0, n);

/** JSON.stringify with sorted keys and no undefined, so equal values always give equal text. */
export function stable(value) {
  if (Array.isArray(value)) return `[${value.map(stable).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.keys(value)
      .filter((k) => value[k] !== undefined)
      .sort()
      .map((k) => `${JSON.stringify(k)}:${stable(value[k])}`)
      .join(",")}}`;
  }
  return JSON.stringify(value) ?? "null";
}

export const fullPath = (root, rel) => path.join(root, ...rel.split("/"));
export const exists = (root, rel) => fs.existsSync(fullPath(root, rel));

export function readJson(root, rel) {
  return JSON.parse(fs.readFileSync(fullPath(root, rel), "utf8"));
}

/** Like readJson, but undefined when the file is not there (a new file the bot is about to make). */
export function readJsonIf(root, rel) {
  return exists(root, rel) ? readJson(root, rel) : undefined;
}

/**
 * Writes JSON the way this repo stores it. Every canon scene, challenge and NPC file already round-trips byte for byte
 * through this (test/tier1-qc-bot.test.mjs checks it), so a patch changes only the lines it means to. A file that
 * used CRLF keeps it.
 */
export function writeJson(root, rel, doc) {
  const full = fullPath(root, rel);
  const crlf = fs.existsSync(full) && fs.readFileSync(full, "utf8").includes("\r\n");
  let text = JSON.stringify(doc, null, 2) + "\n";
  if (crlf) text = text.replace(/\n/g, "\r\n");
  fs.mkdirSync(path.dirname(full), { recursive: true });
  const tmp = `${full}.tmp-${process.pid}`;
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, full);
}

export function listFiles(root, rel, ext) {
  const dir = fullPath(root, rel);
  return fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(ext)).sort() : [];
}

/**
 * What the bot may change in the repo, and how. This is the whole of its write surface (design/qc-bot.md, "Lanes"):
 * `any` = create or change, `modify` = change an existing file only, `add` = create a file that does not exist yet.
 * Nothing else is allowed: not canon facts, plan rows, decisions, the module, the tools, a `.reread.md` record or
 * anything under `data/` that is not a built copy of a scene or challenge, a new person, or the NPC roster.
 */
export const WRITE_RULES = Object.freeze([
  { pattern: /^reviews\/qc\/reports\/[a-z0-9][a-z0-9-]*\/\d{4}-\d{2}-\d{2}-\d+\.(json|md)$/, mode: "any", why: "the bot's own reports" },
  { pattern: /^canon\/(scenes|challenges)\/[a-z0-9][a-z0-9-]*\.json$/, mode: "modify", why: "a scene or its checks (never a new scene)" },
  { pattern: /^data\/(scene-briefs|challenges)\/[a-z0-9][a-z0-9-]*\.json$/, mode: "modify", why: "the built copy of a canon scene or check file" },
  { pattern: /^data\/npcs\/[a-z0-9][a-z0-9-]*\.json$/, mode: "add", why: "a new person only; existing people are never edited" },
  { pattern: /^data\/campaign\/npc-roster\.json$/, mode: "modify", why: "the roster the NPC generator reads" },
  { pattern: /^data\/campaign\/(told-facts|open-decisions|actor-notes)\.json$/, mode: "modify", why: "generated by story build" },
]);

export const writeRuleFor = (file) => WRITE_RULES.find((r) => r.pattern.test(file)) ?? null;

/**
 * Why a change to `file` is not allowed, or null when it is. `status` is git's: A (added), M (modified), D (deleted),
 * R (renamed).
 */
export function writeProblem(file, status) {
  const rule = writeRuleFor(file);
  if (!rule) return `${file} is outside what the QC bot may change`;
  const verb = status === "A" ? "created" : status === "D" ? "deleted" : status === "R" ? "renamed" : "changed";
  const ok = rule.mode === "any" ? status === "A" || status === "M" : rule.mode === "add" ? status === "A" : status === "M";
  return ok ? null : `${file} may not be ${verb} (${rule.why})`;
}

/** The canon file a built copy comes from, or null: data/scene-briefs/x.json is built from canon/scenes/x.json. */
export function canonSourceOf(file) {
  const m = file.match(/^data\/(scene-briefs|challenges)\/([a-z0-9-]+\.json)$/);
  return m ? `canon/${m[1] === "scene-briefs" ? "scenes" : "challenges"}/${m[2]}` : null;
}

/** "scene" | "challenge" | null, for the files whose structure the direction lock watches. */
export function kindOfFile(file) {
  if (/^canon\/scenes\/[^/]+\.json$/.test(file)) return "scene";
  if (/^canon\/challenges\/[^/]+\.json$/.test(file)) return "challenge";
  return null;
}

/** A scene's short name for ids and commit messages: "episode-c1e1--kit-issue" -> "kit-issue". */
export function shortName(sceneId) {
  return String(sceneId).replace(/^(episode-c\d+e\d+|rest|discovery)--/, "");
}
