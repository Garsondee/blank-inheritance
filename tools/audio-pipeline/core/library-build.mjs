/**
 * Building data/audio/library.json. Pure: source facts in, document out.
 *
 * The one property this file exists to protect is IDENTITY. Reservations in
 * the asset registry, review decisions in review.json and every cue ever
 * authored refer to an asset by id — so an id must survive a file being
 * renamed, moved to a different mood folder, or re-downloaded. Matching runs
 * content-first (the same bytes are the same asset wherever they now sit),
 * then path (the same path with edited bytes is still the same asset), and
 * only a genuinely new file gets a new id.
 */

import { uniqueAssetId } from "../../../module/blank-inheritance/scripts/core/audio-library.mjs";

const stemOf = (relPath) =>
  String(relPath)
    .split("/")
    .pop()
    .replace(/\.[^.]+$/, "");

/**
 * Give every scanned source an id.
 *
 * @param {Array<{relPath: string, sha256: string}>} sources
 * @param {object|null} previous  the previous library.json, if any
 * @returns {Map<string, string>} relPath -> id
 */
export function assignIds(sources, previous) {
  const prior = previous?.assets ?? [];
  const bySha = new Map();
  const byPath = new Map();
  for (const entry of prior) {
    if (entry?.source?.sha256 && !bySha.has(entry.source.sha256)) bySha.set(entry.source.sha256, entry.id);
    if (entry?.source?.path) byPath.set(entry.source.path, entry.id);
  }

  const out = new Map();
  const claimed = new Set();
  // Code-unit order, not localeCompare: collation rules differ between
  // machines, and id assignment must not depend on whose laptop ran it.
  const sorted = [...sources].sort((a, b) => (a.relPath < b.relPath ? -1 : a.relPath > b.relPath ? 1 : 0));
  const priorByPath = new Map(prior.filter((e) => e?.source?.path).map((e) => [e.source.path, e]));

  // Pass 1, strongest evidence first, all before any new id is minted (so a
  // new file can never take a slug an old one is about to reclaim):
  //   a) same path AND same bytes — nothing happened to it;
  //   b) same path, different bytes — edited in place;
  //   c) same bytes, different path — moved or renamed.
  // Ordering matters for a duplicated file: the original keeps its id by (a)
  // before the copy can claim it by (c).
  const claim = (src, id) => {
    if (!id || claimed.has(id) || out.has(src.relPath)) return;
    out.set(src.relPath, id);
    claimed.add(id);
  };
  for (const src of sorted) {
    const p = priorByPath.get(`audio/in-tray/${src.relPath}`);
    if (p && p.source.sha256 === src.sha256) claim(src, p.id);
  }
  for (const src of sorted) claim(src, byPath.get(`audio/in-tray/${src.relPath}`));
  for (const src of sorted) claim(src, bySha.get(src.sha256));

  // Pass 2: new ids, unique against everything claimed AND everything the
  // previous library ever used — an id that meant one sound must never be
  // recycled to mean another, or an old reservation would silently repoint.
  const taken = new Set([...claimed, ...prior.map((e) => e.id)]);
  for (const src of sorted) {
    if (out.has(src.relPath)) continue;
    const id = uniqueAssetId(stemOf(src.relPath), taken);
    taken.add(id);
    out.set(src.relPath, id);
  }
  return out;
}

/** Only the loudness numbers worth keeping — not the frame count or scratch fields. */
export function compactAnalysis(analysis) {
  if (!analysis) return null;
  const keep = [
    "integratedLufs",
    "lraLu",
    "truePeakDbtp",
    "maxMomentaryLufs",
    "maxShortTermLufs",
    "leadingSilenceSec",
    "trailingSilenceSec",
    "silentThroughout",
    "decodedDurationSec"
  ];
  const out = {};
  for (const k of keep) if (analysis[k] !== undefined) out[k] = analysis[k];
  return out;
}

/**
 * One library entry. Everything here is regenerated from the bytes on disk
 * on every run; nothing a human decided is ever stored in this file (that is
 * review.json's job), so rewriting it wholesale can never lose a decision.
 */
export function libraryEntry({ id, relPath, sha256, bytes, probe, analysis, proposal, encode = null, output = null }) {
  return {
    id,
    source: {
      path: `audio/in-tray/${relPath}`,
      sha256,
      bytes,
      container: probe?.container ?? null,
      codec: probe?.codec ?? null,
      sampleRate: probe?.sampleRate ?? null,
      channels: probe?.channels ?? null,
      bitRate: probe?.bitRate ?? null,
      durationSec: probe?.durationSec ?? null,
      tags: probe?.tags ?? {}
    },
    analysis: compactAnalysis(analysis),
    proposal,
    encode,
    output
  };
}

/** The whole document, entries in a stable order so diffs stay readable. */
export function libraryDocument({ entries, ffmpegVersion, generatedAt, root }) {
  return {
    $schema: "../schema/audio-library.schema.json",
    id: "audio-library",
    type: "audio-library",
    description:
      "GENERATED by tools/audio-pipeline — do not hand-edit (it is rewritten on every run). What every audio file physically is, how loud it measured, and how it was processed. Human decisions live in review.json; reservations live in data/campaign/asset-registry.json.",
    generatedAt,
    generator: { tool: "tools/audio-pipeline", ffmpeg: ffmpegVersion ?? null },
    root,
    assets: [...entries].sort((a, b) => a.id.localeCompare(b.id))
  };
}

/**
 * Whether an asset's processed file needs (re)building: no encode on record,
 * a different plan than last time, or the file on disk no longer matching the
 * hash recorded when it was written.
 */
export function needsEncode({ plan, previousEncode, outputSha256 }) {
  if (!previousEncode) return { needed: true, reason: "never processed" };
  if (previousEncode.planHash !== plan.hash) return { needed: true, reason: "processing plan changed" };
  if (!outputSha256) return { needed: true, reason: "processed file missing" };
  if (outputSha256 !== previousEncode.sha256) return { needed: true, reason: "processed file changed on disk" };
  return { needed: false, reason: "up to date" };
}

/** A short, human summary of a run, for the terminal. */
export function summariseRun(entries, { encoded = 0, skipped = 0, failed = [] } = {}) {
  const byKind = {};
  let sourceBytes = 0;
  let outputBytes = 0;
  for (const e of entries) {
    const kind = e.proposal?.kind ?? "unknown";
    byKind[kind] = (byKind[kind] ?? 0) + 1;
    sourceBytes += Number(e.source?.bytes) || 0;
    outputBytes += Number(e.encode?.bytes) || 0;
  }
  const mb = (n) => `${(n / 1024 / 1024).toFixed(1)} MB`;
  const lines = [
    `${entries.length} assets: ${Object.entries(byKind)
      .sort()
      .map(([k, n]) => `${n} ${k}`)
      .join(", ")}`,
    `sources ${mb(sourceBytes)} -> processed ${mb(outputBytes)}`,
    `${encoded} encoded this run, ${skipped} already up to date`
  ];
  if (failed.length) lines.push(`${failed.length} FAILED: ${failed.map((f) => f.id ?? f.relPath).join(", ")}`);
  return lines.join("\n");
}
